    def _warn_if_crs_unknown(self):
        """Show a warning dialog if the source layer has no defined CRS."""
        crs = None
        if self.rb_shp.isChecked():
            shp_path = self.le_shp_path.text().strip()
            if shp_path:
                tmp = QgsVectorLayer(shp_path, "_crs_check", "ogr")
                if tmp.isValid():
                    crs = tmp.crs()
        elif self.rb_layer.isChecked() or self.rb_layer_csv.isChecked():
            layer = (
                self._get_selected_layer()
                if self.rb_layer.isChecked()
                else self._get_selected_layer_csv()
            )
            if layer:
                src = layer.source().split("|")[0].strip()
                if src.lower().endswith(".shp") and os.path.isfile(src):
                    tmp = QgsVectorLayer(src, "_crs_check", "ogr")
                    if tmp.isValid():
                        crs = tmp.crs()
                else:
                    crs = layer.crs()

        if crs is not None and not crs.isValid():
            QMessageBox.warning(
                self,
                self.tr("CRS Undefined"),
                self.tr(
                    "The source file has no CRS (coordinate reference system) defined.\n\n"
                    "The conversion will proceed, but the output layer may not display "
                    "correctly on the map.\n\n"
                    "After conversion, right-click the output layer → "
                    "\"Set Layer CRS\" and select the correct CRS manually."
                ),
            )

    def _background_messages(self, output_path):
        """Return translated strings copied before the worker thread starts."""
        return {
            "complete": self.tr("Conversion complete: {}").format(output_path),
            "write_error": self.tr("Write error (code {}): {}"),
            "failed_open_shapefile": self.tr("Failed to open Shapefile."),
            "failed_open_shapefile_source": self.tr("Failed to open Shapefile source."),
            "failed_open_layer_source": self.tr("Failed to open layer source."),
            "failed_read_join_file": self.tr("Failed to read join file."),
        }

    def _build_background_conversion_job(self, output_path):
        """Build a thread-safe conversion job, or None when the path must stay main-threaded."""
        messages = self._background_messages(output_path)
        if self.rb_shp.isChecked():
            shp_path = self.le_shp_path.text().strip()
            return {
                "kind": "shp",
                "output_path": output_path,
                "shp_path": shp_path,
                "codec": self._get_encoding_codec() or "utf-8",
                "layer_name": os.path.splitext(os.path.basename(shp_path))[0],
                "joins": [],
                "messages": messages,
            }

        if self.rb_layer.isChecked():
            layer = self._get_selected_layer()
            if layer is None:
                return None
            source_path = layer.source().split("|")[0].strip()
            if not (source_path.lower().endswith(".shp") and os.path.isfile(source_path)):
                return None
            joins = []
            for join_info in layer.vectorJoins():
                join_layer = QgsProject.instance().mapLayer(join_info.joinLayerId())
                if join_layer is None:
                    continue
                join_path = self._extract_join_source_path(join_layer.source())
                if not join_path:
                    continue
                subset = join_info.joinFieldNamesSubset()
                joins.append({
                    "join_path": join_path,
                    "join_field": join_info.joinFieldName(),
                    "target_idx": layer.fields().indexFromName(join_info.targetFieldName()),
                    "subset": list(subset) if subset else [],
                    "csv_codec": self._get_csv_encoding_codec() or "utf-8",
                })
            return {
                "kind": "shp",
                "output_path": output_path,
                "shp_path": source_path,
                "codec": self._get_encoding_codec() or "utf-8",
                "layer_name": layer.name(),
                "joins": joins,
                "messages": messages,
            }

        if self.rb_layer_csv.isChecked():
            layer = self._get_selected_layer_csv()
            if layer is None:
                return None
            source_path = layer.source().split("|")[0].strip()
            if not (source_path.lower().endswith(".shp") and os.path.isfile(source_path)):
                return None
            return {
                "kind": "shp",
                "output_path": output_path,
                "shp_path": source_path,
                "codec": self._get_encoding_codec() or "utf-8",
                "layer_name": layer.name(),
                "joins": [{
                    "join_path": self.le_csv_path.text().strip(),
                    "join_field": self.cb_csv_field.currentText(),
                    "target_idx": layer.fields().indexFromName(self.cb_layer_field.currentText()),
                    "subset": [],
                    "csv_codec": self._get_csv_encoding_codec() or "utf-8",
                }],
                "messages": messages,
            }

        return None

    def _on_execute_clicked(self):
        """Validate, confirm, convert, and load result into QGIS."""
        _debug_log("_on_execute_clicked start")
        if not self._validate_inputs():
            _debug_log("_on_execute_clicked validation failed")
            return

        output_path = self._select_output_file()
        if not output_path:
            self.lbl_result_summary.setText(
                self.tr("Result: Execution canceled (no output selected).")
            )
            _debug_log("_on_execute_clicked canceled no output")
            return

        if self.rb_layer.isChecked():
            layer = self._get_selected_layer()
            if layer and self._is_layer_source_gpkg(layer) and not self._detect_layer_joins(layer):
                self.lbl_result_summary.setText(
                    self.tr("Result: Layer is already GPKG with no joins. Skipping.")
                )
                QMessageBox.information(
                    self,
                    self.tr("Skip"),
                    self.tr(
                        "This layer is already GPKG and has no joins to reproduce. Skipping."
                    ),
                )
                return

        # Warn if source CRS is undefined
        self._warn_if_crs_unknown()

        self._pending_output_path = output_path

        # Switch UI to progress mode
        self.btn_execute.setVisible(False)
        self.progress_bar.setVisible(True)
        self.lbl_result_summary.setText(self.tr("Result: Converting..."))

        background_job = self._build_background_conversion_job(output_path)
        if background_job is not None:
            self._start_background_conversion(background_job)
            return

        # Fallback path for non-SHP layer flattening. QgsVectorLayer/QgsProject/provider
        # calls are kept on the main QGIS thread to avoid cross-thread crashes.
        QtWidgets.QApplication.processEvents()
        try:
            ok, msg = self._do_convert(output_path)
        except Exception as e:
            ok, msg = False, str(e)
            _debug_log("_on_execute_clicked exception={}".format(e))
        self._on_conversion_done(ok, msg)

    def _start_background_conversion(self, job):
        """Run a conversion job whose inputs are plain paths/strings only."""
        _debug_log("_start_background_conversion kind={}".format(job.get("kind")))
        self.progress_bar.setRange(0, 100)
        self.progress_bar.setValue(0)
        self._thread = QThread(self)
        self._worker = _ConversionWorker(self._do_convert_background, job)
        self._worker.moveToThread(self._thread)
        self._thread.started.connect(self._worker.run)
        self._worker.progress.connect(self._on_conversion_progress)
        self._worker.finished.connect(self._on_conversion_done)
        self._worker.finished.connect(self._thread.quit)
        self._worker.finished.connect(self._worker.deleteLater)
        self._thread.finished.connect(self._thread.deleteLater)
        self._thread.finished.connect(self._on_conversion_thread_finished)
        self._thread.start()

    def _on_conversion_progress(self, value):
        """Update C-group conversion progress from the background worker."""
        try:
            self.progress_bar.setValue(max(0, min(100, int(value))))
        except RuntimeError:
            pass

    def _on_conversion_thread_finished(self):
        """Release background conversion references after QThread cleanup."""
        _debug_log("_on_conversion_thread_finished")
        self._thread = None
        self._worker = None

    def _on_conversion_done(self, ok, msg):
        """Called on the main thread when the background conversion finishes."""
        _debug_log("_on_conversion_done ok={} msg={}".format(ok, msg))
        self.progress_bar.setVisible(False)
        self.progress_bar.setRange(0, 0)
        self.progress_bar.setValue(0)
        self.btn_execute.setVisible(True)
        self.lbl_result_summary.setText(self.tr("Result: {}").format(msg))
        output_path = self._pending_output_path
        if ok:
            # Use the actual internal layer name from the GPKG (not the output filename)
            tmp = QgsVectorLayer(output_path, "tmp", "ogr")
            if tmp.isValid():
                internal_name = tmp.dataProvider().uri().table()
                del tmp
            else:
                internal_name = os.path.splitext(os.path.basename(output_path))[0]
            result_layer = QgsVectorLayer(
                "{}|layername={}".format(output_path, internal_name), internal_name, "ogr"
            )
            if result_layer.isValid():
                QgsProject.instance().addMapLayer(result_layer)
            self._reset_source_selection()
            QMessageBox.information(self, self.tr("Success"), msg)
        else:
            QMessageBox.critical(self, self.tr("Error"), msg)

    # ── Conversion dispatch ───────────────────────────────────────────

    def _do_convert(self, output_path):
        """Dispatch to the appropriate conversion method. Returns (ok, message)."""
        _debug_log("_do_convert start output_path={}".format(output_path))
        if self.rb_shp.isChecked():
            _debug_log("_do_convert branch=shp")
            return self._convert_shp(output_path)
        if self.rb_layer_csv.isChecked():
            _debug_log("_do_convert branch=layer_csv")
            return self._convert_layer_csv(output_path)
        _debug_log("_do_convert branch=layer")
        return self._convert_layer(output_path)

    @classmethod
    def _do_convert_background(cls, job, progress_cb=None):
        """Worker-thread conversion entry point. Uses no QGIS project/layer/widget objects."""
        if progress_cb:
            progress_cb(0)
        if job.get("kind") == "shp":
            return cls._write_shp_job_to_gpkg(job, progress_cb)
        return False, "Unsupported background conversion job."

    @classmethod
    def _load_background_join(cls, join, messages):
        """Read a CSV/XLSX join source inside the worker thread."""
        join_path = join.get("join_path", "")
        join_field = join.get("join_field", "")
        if cls._is_xlsx_path(join_path):
            csv_dict, all_extra_fields = cls._read_xlsx_full(join_path, join_field)
        else:
            csv_dict, all_extra_fields = cls._read_csv_full(
                join_path, join.get("csv_codec") or "utf-8", join_field
            )
        if csv_dict is None:
            return None, None, messages["failed_read_join_file"]

        subset = set(join.get("subset") or [])
        if subset:
            extra_fields = [f for f in all_extra_fields if f in subset]
        else:
            extra_fields = all_extra_fields
        return csv_dict, extra_fields, None

    @staticmethod
    def _background_join_key(value):
        """Normalize join keys the same way as the in-memory merge path."""
        if value is None:
            return ""
        if isinstance(value, float) and value == int(value):
            return str(int(value))
        return str(value).strip()

    @staticmethod
    def _set_ogr_field(feature, index, value):
        """Set an OGR field, leaving None values as NULL."""
        if value is None:
            return
        feature.SetField(index, value)

    @staticmethod
    def _create_ogr_field(ogr, layer, spec):
        """Create one OGR field from a copied plain field spec."""
        ftype = spec.get("ftype")
        flen = spec.get("flen") or 0
        dec_count = spec.get("dec_count") or 0
        if ftype in ("N", "F"):
            field_type = ogr.OFTReal if dec_count > 0 else ogr.OFTInteger64
        elif ftype == "L":
            field_type = ogr.OFTInteger
        else:
            field_type = ogr.OFTString

        field_defn = ogr.FieldDefn(spec["name"], field_type)
        if ftype == "L" and hasattr(ogr, "OFSTBoolean"):
            field_defn.SetSubType(ogr.OFSTBoolean)
        if flen:
            field_defn.SetWidth(flen)
        if dec_count:
            field_defn.SetPrecision(dec_count)
        return layer.CreateField(field_defn)

    @classmethod
    def _write_shp_job_to_gpkg(cls, job, progress_cb=None):
        """Write a SHP-based job to GPKG in a worker thread using GDAL/OGR only."""
        messages = job["messages"]
        shp_path = job["shp_path"]
        output_path = job["output_path"]
        fields, records = cls._read_dbf_full(
            shp_path,
            job.get("codec") or "utf-8",
            progress_cb=progress_cb,
            progress_start=1,
            progress_end=35,
        )
        if progress_cb:
            progress_cb(36)

        try:
            from osgeo import ogr
        except Exception as e:
            return False, messages["write_error"].format("GDAL", e)

        src_ds = ogr.Open(shp_path)
        if src_ds is None:
            return False, messages["failed_open_shapefile"]
        src_layer = src_ds.GetLayer(0)
        if src_layer is None:
            return False, messages["failed_open_shapefile_source"]

        used_names = set()
        output_fields = []
        for name, ftype, flen, dec_count in fields:
            output_fields.append({
                "name": cls._safe_gpkg_name(name, used_names),
                "ftype": ftype,
                "flen": flen,
                "dec_count": dec_count,
            })

        join_data = []
        for join in job.get("joins") or []:
            csv_dict, extra_fields, error = cls._load_background_join(join, messages)
            if error:
                return False, error
            safe_names = []
            for fname in extra_fields:
                safe_name = cls._safe_gpkg_name(fname, used_names)
                safe_names.append(safe_name)
                output_fields.append({
                    "name": safe_name,
                    "ftype": "C",
                    "flen": 0,
                    "dec_count": 0,
                })
            join_data.append({
                "target_idx": join.get("target_idx", -1),
                "csv_dict": csv_dict,
                "extra_fields": extra_fields,
            })
        if progress_cb:
            progress_cb(42)

        driver = ogr.GetDriverByName("GPKG")
        if driver is None:
            return False, messages["write_error"].format("GDAL", "GPKG driver is unavailable.")
        if os.path.exists(output_path):
            try:
                driver.DeleteDataSource(output_path)
            except Exception:  # nosec B110 - best-effort cleanup; a real failure surfaces via the CreateDataSource check below
                pass
        out_ds = driver.CreateDataSource(output_path)
        if out_ds is None:
            return False, messages["write_error"].format("GDAL", "Failed to create output.")

        out_layer = out_ds.CreateLayer(
            job.get("layer_name") or "layer",
            src_layer.GetSpatialRef(),
            src_layer.GetGeomType(),
        )
        if out_layer is None:
            return False, messages["write_error"].format("GDAL", "Failed to create layer.")

        for spec in output_fields:
            err = cls._create_ogr_field(ogr, out_layer, spec)
            if err != 0:
                return False, messages["write_error"].format(err, spec["name"])

        out_defn = out_layer.GetLayerDefn()
        feature_count = src_layer.GetFeatureCount()
        if feature_count <= 0:
            feature_count = len(records)
        write_start = 43
        write_end = 96
        last_progress = write_start - 1
        for i, src_feat in enumerate(src_layer):
            out_feat = ogr.Feature(out_defn)
            geom = src_feat.GetGeometryRef()
            if geom is not None:
                out_feat.SetGeometry(geom.Clone())

            attrs = list(records[i]) if i < len(records) else []
            field_index = 0
            for value in attrs:
                cls._set_ogr_field(out_feat, field_index, value)
                field_index += 1

            for join in join_data:
                target_idx = join["target_idx"]
                raw_key = attrs[target_idx] if 0 <= target_idx < len(attrs) else None
                row = join["csv_dict"].get(cls._background_join_key(raw_key), {})
                for fname in join["extra_fields"]:
                    cls._set_ogr_field(out_feat, field_index, row.get(fname))
                    field_index += 1

            err = out_layer.CreateFeature(out_feat)
            out_feat = None
            if err != 0:
                return False, messages["write_error"].format(err, "Failed to create feature.")
            if progress_cb and feature_count:
                current = write_start + int(((i + 1) / feature_count) * (write_end - write_start))
                if current > last_progress:
                    progress_cb(current)
                    last_progress = current

        if progress_cb:
            progress_cb(98)
        out_layer.SyncToDisk()
        out_ds = None
        src_ds = None
        if progress_cb:
            progress_cb(100)
        return True, messages["complete"]

    def _convert_shp(self, output_path):
        """Convert SHP directly to GPKG using the selected layer encoding."""
        shp_path = self.le_shp_path.text().strip()
        codec = self._get_encoding_codec() or "utf-8"
        layer_name = os.path.splitext(os.path.basename(shp_path))[0]

        fields, records = self._read_dbf_full(shp_path, codec)
        geo_layer = QgsVectorLayer(shp_path, "temp_geom", "ogr")
        if not geo_layer.isValid():
            return False, self.tr("Failed to open Shapefile.")

        mem = self._build_memory_layer(geo_layer, fields, records)
        if mem is None:
            return False, self.tr("Failed to build output layer.")
        return self._write_to_gpkg(mem, output_path, layer_name)

    def _convert_layer(self, output_path):
        """Convert QGIS layer (SHP re-read or flatten with joins) to GPKG."""
        layer = self._get_selected_layer()
        codec = self._get_encoding_codec()
        csv_codec = self._get_csv_encoding_codec()
        layer_name = layer.name()
        source_path = layer.source().split("|")[0].strip()

        if source_path.lower().endswith(".shp") and os.path.isfile(source_path):
            # Re-read SHP with the correct encoding
            fields, records = self._read_dbf_full(source_path, codec or "utf-8")
            geo_layer = QgsVectorLayer(source_path, "temp_geom", "ogr")
            if not geo_layer.isValid():
                return False, self.tr("Failed to open Shapefile source.")
            mem = self._build_memory_layer(geo_layer, fields, records)
            if mem is None:
                return False, self.tr("Failed to build output layer.")

            # Reproduce QGIS-configured joins (e.g., SHP joined to a CSV layer)
            for join_info in layer.vectorJoins():
                join_layer = QgsProject.instance().mapLayer(join_info.joinLayerId())
                if join_layer is None:
                    continue
                join_path = self._extract_join_source_path(join_layer.source())
                if not join_path:
                    continue
                # Field index in original layer → same index in mem (same DBF order)
                target_idx = layer.fields().indexFromName(join_info.targetFieldName())

                # Get the subset of fields selected in the join properties.
                # If this list is empty, it means all fields are joined.
                join_fields_subset = join_info.joinFieldNamesSubset()

                if self._is_xlsx_path(join_path):
                    csv_dict, all_csv_extra_fields = self._read_xlsx_full(
                        join_path, join_info.joinFieldName()
                    )
                else:
                    csv_dict, all_csv_extra_fields = self._read_csv_full(
                        join_path, csv_codec or "utf-8", join_info.joinFieldName()
                    )

                # Filter the fields to be merged based on the join subset.
                # joinFieldNamesSubset() returns the original CSV column names (no prefix).
                # None or empty list means all fields are joined.
                if join_fields_subset:
                    subset_set = set(join_fields_subset)
                    fields_to_merge = [f for f in all_csv_extra_fields if f in subset_set]
                else:
                    fields_to_merge = all_csv_extra_fields

                if csv_dict is not None:
                    # Pass the correctly filtered list of fields to the merge function.
                    mem = self._merge_csv_to_layer(mem, csv_dict, fields_to_merge, target_idx)
                    if mem is None:
                        return False, self.tr("Failed to merge join data.")
        else:
            # GPKG and other formats: iterate features directly (QGIS joins included)
            mem = self._flatten_to_memory(layer)

        if mem is None:
            return False, self.tr("Failed to build output layer.")
        return self._write_to_gpkg(mem, output_path, layer_name)

    def _convert_layer_csv(self, output_path):
        """Join layer with external CSV (separate encodings) and write to GPKG."""
        layer = self._get_selected_layer_csv()
        codec = self._get_encoding_codec()
        csv_codec = self._get_csv_encoding_codec()
        csv_path = self.le_csv_path.text().strip()
        layer_field_name = self.cb_layer_field.currentText()
        csv_field_name = self.cb_csv_field.currentText()

        # Field index is reliable even when the field name is garbled in QGIS
        layer_field_idx = layer.fields().indexFromName(layer_field_name)

        if self._is_xlsx_path(csv_path):
            csv_dict, csv_extra_fields = self._read_xlsx_full(csv_path, csv_field_name)
        else:
            csv_dict, csv_extra_fields = self._read_csv_full(csv_path, csv_codec, csv_field_name)
        if csv_dict is None:
            return False, self.tr("Failed to read join file.")

        source_path = layer.source().split("|")[0].strip()
        if source_path.lower().endswith(".shp") and os.path.isfile(source_path):
            fields, records = self._read_dbf_full(source_path, codec or "utf-8")
            geo_layer = QgsVectorLayer(source_path, "temp_geom", "ogr")
            if not geo_layer.isValid():
                return False, self.tr("Failed to open layer source.")
            base_mem = self._build_memory_layer(geo_layer, fields, records)
        else:
            base_mem = self._flatten_to_memory(layer)

        if base_mem is None:
            return False, self.tr("Failed to build base layer.")

        merged = self._merge_csv_to_layer(base_mem, csv_dict, csv_extra_fields, layer_field_idx)
        if merged is None:
            return False, self.tr("Failed to merge join data.")
        return self._write_to_gpkg(merged, output_path, layer.name())

    # ── Conversion helpers ────────────────────────────────────────────

    @staticmethod
    def _extract_join_source_path(source):
        """Return filesystem path from a QGIS layer source string, or None.

        Handles:
          - Plain file paths:           "/path/to/file.csv"
          - OGR pipe format:            "/path/to/file.shp|layername=..."
          - Delimited text URI:         "file:///path/to/file.csv?delimiter=..."
        """
        if not source:
            return None
        if source.lower().startswith("file:"):
            try:
                from urllib.parse import urlparse, unquote
                parsed = urlparse(source)
                path = unquote(parsed.path)
                # Windows: /C:/path → C:/path
                if path.startswith("/") and len(path) > 2 and path[2] == ":":
                    path = path[1:]
                return path if os.path.isfile(path) else None
            except Exception:  # nosec B110
                pass
        base = source.split("|")[0].strip()
        return base if os.path.isfile(base) else None

    @classmethod
    def _read_dbf_full(cls, shp_path, codec, progress_cb=None, progress_start=0, progress_end=100):
        """Read entire DBF with the given codec.

        Returns (fields, records) where:
          fields  = [(name, ftype, flen, dec_count), ...]
          records = [[val, ...], ...] – deleted records are skipped
        """
        dbf_path = os.path.splitext(shp_path)[0] + ".dbf"
        if not os.path.isfile(dbf_path):
            return [], []
        try:
            with open(dbf_path, "rb") as f:
                hdr = f.read(32)
                if len(hdr) < 32:
                    return [], []
                record_count = int.from_bytes(hdr[4:8], "little")
                header_size = int.from_bytes(hdr[8:10], "little")
                record_size = int.from_bytes(hdr[10:12], "little")
                n_fields = (header_size - 33) // 32
                if progress_cb:
                    progress_cb(progress_start)

                enc = codec or "utf-8"
                fields = []
                offsets = []
                rec_offset = 1  # byte 0 is deletion flag
                f.seek(32)
                for _ in range(n_fields):
                    desc = f.read(32)
                    if len(desc) < 32 or desc[0] == 0x0D:
                        break
                    name_raw = desc[0:11].split(b"\x00")[0]
                    ftype = chr(desc[11])
                    flen = desc[16]
                    dec_count = desc[17]
                    try:
                        name = name_raw.decode(enc, errors="replace").strip()
                    except LookupError:
                        name = name_raw.decode("utf-8", errors="replace").strip()
                    fields.append((name, ftype, flen, dec_count))
                    offsets.append((rec_offset, flen, ftype, dec_count))
                    rec_offset += flen

                records = []
                f.seek(header_size)
                last_progress = progress_start
                for rec_index in range(record_count):
                    record = f.read(record_size)
                    if len(record) < record_size:
                        break
                    if record[0] == 0x2A:  # deleted record — skip (OGR also skips these)
                        continue
                    row = []
                    for foffset, flen, ftype, dec_count in offsets:
                        raw = record[foffset: foffset + flen]
                        try:
                            val = raw.decode(enc, errors="replace").strip()
                        except LookupError:
                            val = raw.decode("utf-8", errors="replace").strip()
                        if ftype in ("N", "F"):
                            if val:
                                try:
                                    val = float(val) if dec_count > 0 else int(float(val))
                                except (ValueError, OverflowError):
                                    pass
                            else:
                                val = None
                        elif ftype == "L":
                            val = (
                                True if val.upper() in ("T", "Y")
                                else (False if val.upper() in ("F", "N") else None)
                            )
                        row.append(val)
                    records.append(row)
                    if progress_cb and record_count:
                        current = progress_start + int(
                            ((rec_index + 1) / record_count) * (progress_end - progress_start)
                        )
                        if current > last_progress:
                            progress_cb(current)
                            last_progress = current
            return fields, records
        except Exception:
            return [], []

    # GPKG uses "fid" as the primary key column and "geom"/"geometry" for geometry.
    # Fields with these names must be renamed to avoid silent data loss or misalignment.
    _GPKG_RESERVED = frozenset({"fid", "geom", "geometry"})
    
    # Suffixes for resolving duplicate field names, per user suggestion for readability.
    _DUPLICATE_SUFFIXES = [
        '_α', '_β', '_γ', '_δ', '_ε', '_ζ', '_η', '_θ', '_ι', '_κ', '_λ', '_μ',
        '_ν', '_ξ', '_ο', '_π', '_ρ', '_σ', '_τ', '_υ', '_φ', '_χ', '_ψ', '_ω'
    ]
    
    @classmethod
    def _safe_gpkg_name(cls, name, used):
        """Return name safe for GPKG; append suffixes for reserved names or duplicates."""
        # 1. Handle reserved words first by setting the base name
        base_name = (name + "_") if name.lower() in cls._GPKG_RESERVED else name

        # 2. Check if the base name itself is unique
        if base_name.lower() not in used:
            used.add(base_name.lower())
            return base_name

        # 3. If not, try appending Greek letter suffixes
        for suffix in cls._DUPLICATE_SUFFIXES:
            candidate = base_name + suffix
            if candidate.lower() not in used:
                used.add(candidate.lower())
                return candidate

        # 4. Fallback: if all Greek letters are used, append numbers
        i = 1
        while True:
            candidate = "{}_{}".format(base_name, i)
            if candidate.lower() not in used:
                used.add(candidate.lower())
                return candidate
            i += 1

    @classmethod
    def _build_memory_layer(cls, geo_layer, fields, records):
        """Create a memory QgsVectorLayer from geometry + decoded DBF fields/records."""
        geom_str = QgsWkbTypes.displayString(geo_layer.wkbType())
        crs = geo_layer.crs().authid()
        mem = QgsVectorLayer("{}?crs={}".format(geom_str, crs), "output", "memory")
        if not mem.isValid():
            return None

        used_names = set()
        qgs_fields = []
        for name, ftype, flen, dec_count in fields:
            safe = cls._safe_gpkg_name(name, used_names)
            if ftype in ("N", "F"):
                if dec_count > 0:
                    qgs_fields.append(QgsField(safe, QMetaType.Type.Double, '', flen, dec_count))
                else:
                    qgs_fields.append(QgsField(safe, QMetaType.Type.LongLong))
            elif ftype == "L":
                qgs_fields.append(QgsField(safe, QMetaType.Type.Bool))
            else:
                qgs_fields.append(QgsField(safe, QMetaType.Type.QString, '', flen))

        pr = mem.dataProvider()
        pr.addAttributes(qgs_fields)
        mem.updateFields()

        new_feats = []
        for i, geo_feat in enumerate(geo_layer.getFeatures()):
            feat = QgsFeature(mem.fields())
            feat.setGeometry(geo_feat.geometry())
            if i < len(records):
                for j, val in enumerate(records[i]):
                    feat.setAttribute(j, val)
            new_feats.append(feat)
        pr.addFeatures(new_feats)
        mem.updateExtents()
        return mem

    @classmethod
    def _flatten_to_memory(cls, layer):
        """Copy layer (including virtual join fields) to a memory layer."""
        geom_str = QgsWkbTypes.displayString(layer.wkbType())
        crs = layer.crs().authid()
        mem = QgsVectorLayer("{}?crs={}".format(geom_str, crs), "output", "memory")
        if not mem.isValid():
            return None

        used_names = set()
        safe_fields = []
        for field in layer.fields():
            safe_name = cls._safe_gpkg_name(field.name(), used_names)
            new_field = QgsField(field)
            new_field.setName(safe_name)
            safe_fields.append(new_field)

        pr = mem.dataProvider()
        pr.addAttributes(safe_fields)
        mem.updateFields()

        new_feats = []
        for src_feat in layer.getFeatures():
            feat = QgsFeature(mem.fields())
            feat.setGeometry(src_feat.geometry())
            feat.setAttributes(src_feat.attributes())
            new_feats.append(feat)
        pr.addFeatures(new_feats)
        mem.updateExtents()
        return mem

    @staticmethod
    def _read_csv_full(csv_path, codec, key_field):
        """Read CSV into a lookup dict keyed by key_field values.

        Returns (csv_dict, extra_field_names) or (None, None) on error.
        """
        enc = codec or "utf-8"
        try:
            with open(csv_path, "r", encoding=enc, errors="replace") as f:
                reader = csv.DictReader(f)
                headers = list(reader.fieldnames or [])
                csv_dict = {}
                for row in reader:
                    key = str(row.get(key_field, "") or "").strip()
                    csv_dict[key] = dict(row)
            # Deduplicate while preserving order; duplicate CSV columns cause _α suffixes.
            seen = {key_field}
            extra_fields = []
            for h in headers:
                if h not in seen:
                    seen.add(h)
                    extra_fields.append(h)
            return csv_dict, extra_fields
        except Exception:
            return None, None

    @classmethod
    def _merge_csv_to_layer(cls, base_layer, csv_dict, csv_extra_fields, field_idx):
        """Add CSV columns to base_layer joined on the attribute at field_idx."""
        geom_str = QgsWkbTypes.displayString(base_layer.wkbType())
        crs = base_layer.crs().authid()
        mem = QgsVectorLayer("{}?crs={}".format(geom_str, crs), "output", "memory")
        if not mem.isValid():
            return None

        pr = mem.dataProvider()
        # Deduplicate CSV field names against base fields (and GPKG reserved names).
        # Memory provider silently skips duplicate names, which would shift all
        # subsequent CSV columns to wrong positions.
        used_names = {f.name().lower() for f in base_layer.fields()}
        safe_csv_names = [cls._safe_gpkg_name(fname, used_names) for fname in csv_extra_fields]

        new_attrs = list(base_layer.fields())
        for safe_name in safe_csv_names:
            new_attrs.append(QgsField(safe_name, QMetaType.Type.QString))
        pr.addAttributes(new_attrs)
        mem.updateFields()

        # Number of base attributes to copy (trim any extras from virtual join fields).
        n_base = len(base_layer.fields())

        new_feats = []
        for src_feat in base_layer.getFeatures():
            feat = QgsFeature(mem.fields())
            feat.setGeometry(src_feat.geometry())
            # Limit to exactly base-field count so QGIS virtual-join values don't
            # occupy the CSV column slots.
            attrs = list(src_feat.attributes())[:n_base]
            raw_key = src_feat.attribute(field_idx) if field_idx >= 0 else None
            if raw_key is None:
                join_key = ""
            elif isinstance(raw_key, float) and raw_key == int(raw_key):
                join_key = str(int(raw_key))  # 1.0 → "1" not "1.0"
            else:
                join_key = str(raw_key).strip()
            csv_row = csv_dict.get(join_key, {})
            for fname in csv_extra_fields:  # original names for dict lookup
                attrs.append(csv_row.get(fname))
            feat.setAttributes(attrs)
            new_feats.append(feat)
        pr.addFeatures(new_feats)
        mem.updateExtents()
        return mem

    @staticmethod
    def _write_to_gpkg(layer, output_path, layer_name):
        """Write layer to GPKG as UTF-8. Returns (ok, message)."""
        options = QgsVectorFileWriter.SaveVectorOptions()
        options.driverName = "GPKG"
        options.fileEncoding = "UTF-8"
        options.layerName = layer_name or "layer"
        options.actionOnExistingFile = QgsVectorFileWriter.ActionOnExistingFile.CreateOrOverwriteFile

        result, msg, _, _ = QgsVectorFileWriter.writeAsVectorFormatV3(
            layer, output_path, QgsCoordinateTransformContext(), options
        )
        if result == QgsVectorFileWriter.WriterError.NoError:
            return True, QCoreApplication.translate(
                "MultiEncodeVectorConverterDockWidget",
                "Conversion complete: {}"
            ).format(output_path)
        return False, QCoreApplication.translate(
            "MultiEncodeVectorConverterDockWidget",
            "Write error (code {}): {}"
        ).format(result, msg)

